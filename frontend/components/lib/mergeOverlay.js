/* 手で書いた店の情報に、巡回が集めた情報を重ねる。
 *
 * ■ なぜ「欄ごと」なのか
 *
 * 以前は店ごと丸ごと置き換えていた。巡回が作るのは種データに無い店だけなので
 * それで足りていたが、種データにある店へ1欄だけ足したいときに使えない。
 *
 * 実測: Instagram のアカウント名を318店ぶん集めたのに、図鑑に出たのは
 * 巡回で見つけた9店だけだった。残り299店は種データ側にあり、
 * オーバーレイに載らないので永久に出ないままだった。
 *
 * 欄ごとに重ねれば、手で書いた街・座標・紹介文を残したまま、
 * 巡回側が持っている欄（instagram など）だけを足せる。
 *
 * ■ 重ねる向き
 *
 * 巡回側が勝つ。実データの方が新しいという前提は今までと同じ。
 * ただし巡回側に無い欄は、手で書いたものがそのまま残る。
 */
export function mergeOverlay(seeded, live) {
  const out = { ...(seeded || {}) };
  for (const [key, over] of Object.entries(live || {})) {
    out[key] = out[key] ? { ...out[key], ...over } : over;
  }
  return out;
}
